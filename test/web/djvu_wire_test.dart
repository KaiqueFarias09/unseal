void main() {
  test('browser parses a JPEG DjVu and preserves pages over worker wire', () {
    expect(imageSize(tinyJpeg)?.width, 8);
    expect(sniffImageType(tinyJpeg), ImageType.jpeg);
    final bytes = djvuJpegPage(tinyJpeg, text: 'Browser OCR');
    final book = Unseal.parse(bytes) as DjvuBook;
    final (json, blobs) = encodeBookWire(book);
    final decoded = decodeBookWire(json, blobs) as DjvuBook;
    expect(decoded.pageCount, 1);
    expect(decoded.pages.single.text, 'Browser OCR');
    expect(decoded.pages.single.image.content, tinyJpeg);
    expect(decoded.bytes, bytes);
    expect(decoded.readingOrder.single.isHtml, isTrue);
    expect(decoded.search('OCR').matches, hasLength(1));
    expect(
      decodeErrorWire('DjvuUnsupportedCodecException', 'codec'),
      isA<DjvuUnsupportedCodecException>(),
    );
  });

  test('browser displays a JB2 BMP mask and preserves it over worker wire', () async {
    final bytes = licensedDjvuJb2Page();
    final book = Unseal.parse(bytes) as DjvuBook;
    expect(book.pages.single.width, 2550);
    expect(book.pages.single.height, 3301);
    expect(book.pages.single.image.type, 'bmp');
    expect(sniffImageType(book.pages.single.image.content), ImageType.bmp);
    expect(imageSize(book.pages.single.image.content), const ImageSize(2550, 3301));

    await _expectBrowserBmp(book.pages.single.image.content, 2550, 3301);

    final (json, blobs) = encodeBookWire(book);
    final decoded = decodeBookWire(json, blobs) as DjvuBook;
    expect(decoded.pages.single.image.content, book.pages.single.image.content);
    expect(decoded.bytes, bytes);
    expect(decoded.files.html.single.content, contains('../images/page-1.bmp'));
  });

  test('browser keeps TXTz hidden text and NAVM navigation over worker wire', () {
    // Verbatim compressed chunks from the tracked public-domain corpus
    // (PROVENANCE.md): cyrillic.djvu page 1's TXTz and links.djvu's NAVM.
    final txtz = base64Decode(_cyrillicTxtzBase64);
    final navm = base64Decode(_linksNavmBase64);
    final book =
        Unseal.parse(djvuBundleWithOutline(<Uint8List>[djvuJpegPage(tinyJpeg, txtz: txtz)], navm))
            as DjvuBook;
    expect(book.pages.single.text, startsWith('(ЩУ И МШИ'));
    expect(book.navigation.navPoints, hasLength(2));

    final (json, blobs) = encodeBookWire(book);
    final decoded = decodeBookWire(json, blobs) as DjvuBook;
    expect(decoded.pages.single.text, book.pages.single.text);
    expect(decoded.navigation.navPoints.map((final point) => point.label), <String>[
      'Relative Link',
      'Absolute Link',
    ]);
    expect(decoded.navigation.navPoints[0].content, 'colorbook.djvu');
    expect(
      decoded.navigation.navPoints[1].content,
      'https://djvu.js.org/assets/djvu_examples/DjVu3Spec.djvu',
    );
  });

  test('browser decodes a real grayscale IW44 page and preserves it over worker wire', () async {
    final bytes = licensedDjvuIw44GrayPage();
    final book = Unseal.parse(bytes) as DjvuBook;
    final image = book.pages.single.image;

    expect(image.type, 'bmp');
    expect(imageSize(image.content), const ImageSize(192, 256));
    await _expectBrowserBmp(image.content, 192, 256);

    final (json, blobs) = encodeBookWire(book);
    final decoded = decodeBookWire(json, blobs) as DjvuBook;
    expect(decoded.pages.single.image.content, image.content);
    expect(decoded.bytes, bytes);
  });
}

Future<void> _expectBrowserBmp(final List<int> bytes, final int width, final int height) async {
  final imageLoaded = Completer<void>();
  final imageElement = web.document.createElement('img') as web.HTMLImageElement;
  imageElement.addEventListener(
    'load',
    ((web.Event _) {
      if (!imageLoaded.isCompleted) imageLoaded.complete();
    }).toJS,
  );
  imageElement.addEventListener(
    'error',
    ((web.Event _) {
      if (!imageLoaded.isCompleted) {
        imageLoaded.completeError(StateError('Chrome could not decode the generated DjVu BMP.'));
      }
    }).toJS,
  );
  imageElement.src = 'data:image/bmp;base64,${base64Encode(bytes)}';
  await imageLoaded.future.timeout(const Duration(seconds: 10));
  expect(imageElement.naturalWidth, width);
  expect(imageElement.naturalHeight, height);
}
