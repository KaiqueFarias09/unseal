/// Fixed seed shared by every large-fixture generator. Changing it
/// changes every generated byte.
const int fixtureSeed = 0x5EED2026;

/// Deterministic 64-bit PRNG (SplitMix64). One instance per generator;
/// never share one across concurrently-written files so chapter order
/// cannot change a chapter's content.
final class SplitMix64 {
  /// Creates a generator from a non-negative [seed].
  ///
  /// The state doubles as the seed and [next] advances it by the golden
  /// gamma before mixing, so any seed (including zero) starts a
  /// full-period stream.
  SplitMix64(final int seed) : state = seed;

  /// The mutable state; the initial value is the seed.
  int state;

  /// The next 64-bit value (two's complement, as Dart's `int` holds it).
  int next() {
    state = (state + 0x9E3779B97F4A7C15) & _mask64;
    var z = state;
    z = ((z ^ (z >>> 30)) * 0xBF58476D1CE4E5B9) & _mask64;
    z = ((z ^ (z >>> 27)) * 0x94D049BB133111EB) & _mask64;
    return (z ^ (z >>> 31)) & _mask64;
  }

  /// A uniform integer in `[0, maxExclusive)`.
  int below(final int maxExclusive) {
    if (maxExclusive <= 0) {
      throw ArgumentError.value(maxExclusive, 'maxExclusive', 'must be positive');
    }
    return (next() >>> 1) % maxExclusive;
  }

  /// One byte.
  int byte() => next() & 0xFF;
}

const int _mask64 = 0xFFFFFFFFFFFFFFFF;

/// A random-ish pixel pattern whose deflate stream stays at the raw
/// size, so PNG bytes approximate a real scanned page.
Uint8List buildNoisePng({
  required final int width,
  required final int height,
  required final SplitMix64 random,
}) {
  // The builder MUST copy: rows are refilled in place, and a builder
  // that keeps references would deflate one shared row to nothing.
  final raw = BytesBuilder(copy: true);
  final row = Uint8List(1 + width * 3);
  for (var y = 0; y < height; y++) {
    row[0] = 0; // filter: none
    for (var x = 0; x < width * 3; x++) {
      row[1 + x] = random.byte();
    }
    raw.add(row);
  }
  final idat = ZLibEncoder().encodeBytes(raw.toBytes(), level: 6);

  final png = BytesBuilder(copy: false);
  png.add(const [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]);
  png.add(_chunk('IHDR', _ihdr(width, height)));
  png.add(_chunk('IDAT', idat));
  png.add(_chunk('IEND', Uint8List(0)));
  return png.toBytes();
}

Uint8List _ihdr(final int width, final int height) {
  final data = Uint8List(13);
  final view = ByteData.view(data.buffer);
  view.setUint32(0, width);
  view.setUint32(4, height);
  data[8] = 8; // bit depth
  data[9] = 2; // color type: truecolor RGB
  data[10] = 0; // deflate
  data[11] = 0; // adaptive filtering
  data[12] = 0; // no interlace
  return data;
}

/// One PNG chunk: big-endian length, type, data, CRC-32 over type+data.
Uint8List _chunk(final String type, final Uint8List data) {
  final chunk = Uint8List(12 + data.length);
  final view = ByteData.view(chunk.buffer);
  view.setUint32(0, data.length);
  for (var i = 0; i < 4; i++) {
    chunk[4 + i] = type.codeUnitAt(i);
  }
  chunk.setRange(8, 8 + data.length, data);
  view.setUint32(8 + data.length, _crc32(chunk.sublist(4, 8 + data.length)));
  return chunk;
}

/// CRC-32 (IEEE 802.3), the PNG polynomial, computed bitwise. The table
/// version saves microseconds that this tool never needs.
int _crc32(final List<int> bytes) {
  var crc = 0xFFFFFFFF;
  for (final byte in bytes) {
    crc ^= byte;
    for (var bit = 0; bit < 8; bit++) {
      final mask = -(crc & 1);
      crc = (crc >> 1) ^ (0xEDB88320 & mask);
    }
  }
  return (~crc) & 0xFFFFFFFF;
}

/// Packs [entries] into a zip. [firstStoredEntry], when given, is written
/// first WITHOUT compression (the EPUB `mimetype` convention); every
/// other entry deflates. Modification times are pinned so the bytes are
/// reproducible.
Uint8List buildZip(final Map<String, List<int>> entries, {final String? firstStoredEntry}) {
  final archive = Archive();
  void add(final String name, final List<int> bytes, {required final bool stored}) {
    final data = Uint8List.fromList(bytes);
    final file = ArchiveFile(name, data.length, data)
      ..lastModTime = 946684800
      ..compression = stored ? CompressionType.none : CompressionType.deflate;
    archive.addFile(file);
  }

  if (firstStoredEntry != null) {
    final bytes = entries[firstStoredEntry];
    if (bytes == null) {
      throw ArgumentError('firstStoredEntry $firstStoredEntry is missing from entries');
    }
    add(firstStoredEntry, bytes, stored: true);
  }
  for (final entry in entries.entries) {
    if (entry.key == firstStoredEntry) {
      continue;
    }
    add(entry.key, entry.value, stored: false);
  }
  return Uint8List.fromList(ZipEncoder().encode(archive));
}

/// Varied English prose from a fixed word bag, generated sentence by
/// sentence. Long paragraphs appear roughly one time in five so the
/// text exercises both small and large block layout.
String generateChapterBody({
  required final int chapterNumber,
  required final SplitMix64 random,
  required final int minimumCharacters,
}) {
  final prose = StringBuffer();
  void paragraph(final int sentences) {
    for (var s = 0; s < sentences; s++) {
      prose.write(_sentence(random));
    }
    prose.write('\n\n');
  }

  prose.write('<h1>Chapter $chapterNumber</h1>\n\n');
  paragraph(2 + random.below(4));
  while (prose.length < minimumCharacters) {
    // One in five paragraphs runs long; the rest stay short.
    final long = random.below(5) == 0;
    paragraph(long ? 18 + random.below(20) : 3 + random.below(9));
  }
  return prose.toString();
}

