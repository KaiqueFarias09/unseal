// Shared building blocks for the large synthetic book generators
// (generate_large_epub.dart, generate_large_cbz.dart). Not a program:
// import it, never run it.
//
// Everything here is deterministic: the only randomness is
// [SplitMix64] seeded from the generator's fixed seed, so the same
// command produces byte-identical fixtures on the same SDK. PNG data is
// written by hand (signature + IHDR + noise IDAT + IEND) so the images
// are valid enough for signature sniffing and header parsing while
// staying close to the compressed size of real scanned pages — solid
// colors would deflate to a few kilobytes and stop measuring the
// archive path.
//
// Output convention: fixtures land in `build/fixtures/` by default.
// `build/` is git-ignored in this repository and excluded from the
// analyzer; generated fixtures never become tracked resources.

import 'dart:typed_data';

import 'package:archive/archive.dart';

