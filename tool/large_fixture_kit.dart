String _sentence(final SplitMix64 random) {
  final length = 6 + random.below(20);
  final words = StringBuffer();
  for (var i = 0; i < length; i++) {
    if (i > 0) {
      words.write(' ');
    }
    words.write(_words[random.below(_words.length)]);
  }
  // Occasional mid-sentence comma for natural clause rhythm.
  var sentence = words.toString();
  if (length > 10 && random.below(3) == 0) {
    final cut = 3 + random.below(length - 6);
    final pieces = sentence.split(' ');
    pieces[cut] = '${pieces[cut]},';
    sentence = pieces.join(' ');
  }
  return '$sentence. ';
}
