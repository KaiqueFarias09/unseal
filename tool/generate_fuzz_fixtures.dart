// Deterministic structurally-valid fuzz fixture generator.
//
// Builds every committed fixture under test/resources/fuzz/generated/
// from fixed seeds. Hermetic: no network, no clock, no randomness
// beyond the seeds. `--check` regenerates in memory and byte-compares
// with the committed files (CI-safe drift gate).
//
//     dart run tool/generate_fuzz_fixtures.dart            # (re)write
//     dart run tool/generate_fuzz_fixtures.dart --check    # verify only
//     dart run tool/generate_fuzz_fixtures.dart --out=DIR  # alternate dir
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'fuzz/cfi_strings.dart';
import 'fuzz/epub_generator.dart';
