#!/usr/bin/env python3
"""Generate test/support/opds2_shared_cases.dart for the C05 mission.

The file embeds every corpus fixture and its pinned expectation as Dart
string constants so the same positive, negative, and normative cases run
on the VM and in Chrome (where file reads are unavailable). The content
comes from test/resources/opds/feeds and test/resources/opds/expected —
both pinned by the Python oracle. Regenerate with:

  <campaign venv python> tool/opds2_shared_cases.py --worktree . --write

and commit the result together with the corpus change.
"""

import argparse
import json
from pathlib import Path


def dart_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace("'", r"\'")
        .replace("$", r"\$")
        .replace("\n", r"\n")
    )
    return f"'{escaped}'"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--worktree", required=True)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()

    worktree = Path(args.worktree).resolve()
    resources = worktree / "test/resources/opds"
    manifest = json.loads((resources / "corpus-manifest.json").read_text())
    rows = [row for row in manifest["feeds"] if row["kind"] in ("positive", "negative", "normative-only")]

    blocks = []
    for row in rows:
        source = (resources / "feeds" / row["name"]).read_text(encoding="utf-8")
        expected_json = None
        if row["kind"] == "positive":
            expected_json = (resources / "expected" / f"{row['name']}.expected.json").read_text(encoding="utf-8")
        fields = [
            f"    name: {dart_string(row['name'])},",
            f"    kind: {dart_string(row['kind'])},",
            f"    source: {dart_string(source)},",
        ]
        if expected_json is not None:
            fields.append(f"    expectedSummaryJson: {dart_string(expected_json)},")
        blocks.append("  Opds2SharedCase(\n" + "\n".join(fields) + "\n  )")

    cases = ",\n".join(blocks)
    content = f"""// GENERATED by tool/opds2_shared_cases.py — do not edit by hand.
//
// The corpus comes from test/resources/opds (pinned by corpus-manifest.json)
// and the expectations from the Python schema oracle. The VM corpus test
// re-checks this file against the on-disk expectations, so an edit without
// regenerating fails there.
//
// Embedding the cases keeps the Chrome suite byte-equal to the VM suite:
// browser tests cannot read fixture files.

/// One OPDS 2.0 corpus case shared by the VM and Chrome suites.
final class Opds2SharedCase {{
  /// Creates a case.
  const Opds2SharedCase({{
    required this.name,
    required this.kind,
    required this.source,
    this.expectedSummaryJson,
  }});

  /// Fixture file name inside test/resources/opds/feeds.
  final String name;

  /// `positive`, `negative`, or `normative-only`.
  final String kind;

  /// The exact fixture bytes as a string.
  final String source;

  /// Pinned expectation summary for positive cases.
  final String? expectedSummaryJson;
}}

/// The corpus cases.
const List<Opds2SharedCase> opds2SharedCases = <Opds2SharedCase>[
{cases}
];

/// Relative-resolution expectations from the Python urljoin reference.
const String opds2SharedResolutionJson = {dart_string((resources / 'expected/resolution.json').read_text(encoding='utf-8'))};
"""

    target = worktree / "test/support/opds2_shared_cases.dart"
    if args.write:
        target.write_text(content, encoding="utf-8")
        print(f"wrote {target} ({len(content)} bytes, {len(rows)} cases)")
    else:
        if target.read_text(encoding="utf-8") != content:
            raise SystemExit("shared cases are stale; regenerate with --write")
        print("shared cases are current")


if __name__ == "__main__":
    main()
